import math
import random

# multiply
print(2 * 2)

# decimal division
print(5 / 2)

# integer division
print(5 // 2)

# exponent
print(2 ** 2)

# greatest common denominator
print(math.gcd(15, 5))

# rounds up
print(math.ceil(4.2))

# rounds down
print(math.floor(3.2))

# prints random decimal less than 1
print(random.random())

# prints random integer within given range
print(random.randint(1, 3))

# % returns the remainder of a division
print(7%4)